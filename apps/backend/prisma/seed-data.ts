export interface SeedComponent {
  nombre: string;
  slug: string;
  sku: string;
  descripcion: string;
  marcaSlug: string;
  categoriaSlug: string;
  precio: number;
  stock: number;
  especificaciones: Record<string, unknown>;
  datosTecnicos: Record<string, unknown>;
  metadata: Record<string, unknown>;
}

const SKU_PREFIX: Record<string, string> = {
  cpu: 'CPU',
  motherboard: 'MB',
  ram: 'RAM',
  gpu: 'GPU',
  storage: 'STO',
  psu: 'PSU',
  case: 'CSE',
  cooler: 'COL',
};

const slugify = (value: string): string =>
  value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

let seq = 0;

function base(
  categoriaSlug: string,
  marcaSlug: string,
  nombre: string,
  precio: number,
  stock: number,
  descripcion: string,
  especificaciones: Record<string, unknown>,
  datosTecnicos: Record<string, unknown>,
  metadata: Record<string, unknown>,
): SeedComponent {
  const slug = slugify(`${marcaSlug} ${nombre}`);
  seq += 1;
  return {
    nombre,
    slug,
    sku: `${SKU_PREFIX[categoriaSlug]}-${String(seq).padStart(4, '0')}`,
    marcaSlug,
    categoriaSlug,
    precio,
    stock,
    descripcion,
    especificaciones,
    datosTecnicos,
    metadata,
  };
}

const gama = (score: number): string =>
  score >= 30000 ? 'HIGH_END' : score >= 18000 ? 'MID_RANGE' : 'ENTRY';

const cpu = (
  marca: string,
  nombre: string,
  socket: string,
  ramType: string,
  nucleos: number,
  hilos: number,
  frecuenciaBase: number,
  frecuenciaTurbo: number,
  tdp: number,
  score: number,
  precio: number,
): SeedComponent =>
  base(
    'cpu',
    marca,
    nombre,
    precio,
    Math.max(5, Math.round(40000 / precio)),
    `Procesador ${nucleos} núcleos / ${hilos} hilos para socket ${socket}.`,
    { socket, ramType, nucleos, hilos, frecuenciaBase, frecuenciaTurbo, tdp },
    { socket, ramType, tdp, benchmarkScore: score },
    { gama: gama(score), sockets: [socket] },
  );

const mb = (
  marca: string,
  nombre: string,
  socket: string,
  tipoRam: string,
  factorForma: string,
  chipset: string,
  slotsRam: number,
  maxRam: number,
  precio: number,
): SeedComponent =>
  base(
    'motherboard',
    marca,
    nombre,
    precio,
    Math.max(4, Math.round(3000 / precio)),
    `Placa madre ${factorForma} con socket ${socket}, ${tipoRam} y chipset ${chipset}.`,
    { socket, tipoRam, factorForma, chipset, slotsRam, maxRam },
    { socket, tipoRam, chipset, factorForma },
    {},
  );

const ram = (
  marca: string,
  nombre: string,
  tipo: string,
  capacidad: number,
  modulos: number,
  frecuencia: number,
  latencia: string,
  precio: number,
): SeedComponent =>
  base(
    'ram',
    marca,
    nombre,
    precio,
    Math.max(5, Math.round(1600 / precio)),
    `Kit de memoria ${tipo} de ${capacidad}GB (${modulos} módulos) a ${frecuencia}MHz ${latencia}.`,
    { tipo, capacidad, modulos, frecuencia, latencia },
    { tipo, capacidad, frecuencia, latencia },
    {},
  );

const gpu = (
  marca: string,
  nombre: string,
  vram: number,
  tdp: number,
  longitud: number,
  bus: string,
  score: number,
  precio: number,
): SeedComponent =>
  base(
    'gpu',
    marca,
    nombre,
    precio,
    Math.max(3, Math.round(20000 / precio)),
    `Tarjeta gráfica con ${vram}GB de VRAM, ${tdp}W de TDP y ${longitud}mm de longitud.`,
    { vram, tdp, longitud, bus },
    { vram, tdp, longitud, benchmarkScore: score },
    { gama: gama(score) },
  );

