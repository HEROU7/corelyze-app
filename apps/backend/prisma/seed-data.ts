  base(
    'case',
    marca,
    nombre,
    precio,
    Math.max(4, Math.round(2000 / precio)),
    `Gabinete ${factorForma} con soporte para GPU de hasta ${maxGpuLength}mm.`,
    { factorForma, maxGpuLength, maxCoolerHeight, slots },
    { factorForma, maxGpuLength, maxCoolerHeight },
    {},
  );

